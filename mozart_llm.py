# ---------------------------------------------------------------------------
# generate_alignment_summary()
# ---------------------------------------------------------------------------

def generate_alignment_summary(
    alignment: AlignmentResult,
    raw_metrics: dict[str, Optional[float]],
    max_tokens: int = 350,
) -> str:
    """
    Генерирует 3–5 предложений описания текущего состояния рынка
    на основе активных сигналов Mozart и числовых метрик.

    Args:
        alignment:   AlignmentResult из mozart_alignment.build_alignment().
        raw_metrics: Словарь числовых значений метрик.
                     Значения None → фильтруются, не попадают в промпт.
        max_tokens:  Максимум токенов ответа (default: 350 ≈ 3–5 предложений).

    Returns:
        str: 3–5 предложений на русском языке.
             НЕ содержит рекомендаций, советов, прогнозов цены.

    Raises:
        google.genai.errors.APIError: при проблемах с API.
            Оркестратор оборачивает вызов в try/except.

    TDD:
        Только smoke-test (tests/test_mozart_llm_smoke.py).
        Smoke: str, len > 50, нет 'None', нет слов-рекомендаций, 1 вызов API.
    """
    # --- Шаг 1: контекст только из активных сигналов ---
    active_ids = alignment.bullish + alignment.bearish + alignment.neutral
    context_lines: list[str] = []

    for sid in active_ids:
        ctx = SIGNAL_CONTEXT.get(sid)
        if ctx is None:
            continue   # МБ-03 и другие без контекста

        if sid in alignment.bullish:
            polarity = 'BULLISH'
        elif sid in alignment.bearish:
            polarity = 'BEARISH'
        else:
            polarity = 'NEUTRAL'

        contr_tag = ' [КОНТРАРИАНСКИЙ]' if sid in alignment.contrarian_flags else ''
        context_lines.append(f"  {sid} ({polarity}{contr_tag}): {ctx}")

    missing_str = ', '.join(alignment.missing) if alignment.missing else 'нет'
    context_str = (
        '\n'.join(context_lines)
        if context_lines
        else '  (нет активных сигналов с описанием)'
    )

    # --- Шаг 2: числовые метрики — только не-None ---
    metrics_lines = [
        f"  {k}: {v}"
        for k, v in raw_metrics.items()
        if v is not None
    ]
    metrics_str = '\n'.join(metrics_lines) if metrics_lines else '  (данные недоступны)'

    # --- Шаг 3: промпт ---
    prompt = (
        "Ты аналитический ассистент криптовалютного трейдера.\n"
        "Используй только методологию аналитика Mozart (цитаты из его постов ниже).\n\n"
        "ПРАВИЛА ВЫВОДА — строго обязательны:\n"
        "- Только факты и определения метрик по методологии Mozart\n"
        "- Никаких торговых рекомендаций, советов, призывов к действию\n"
        "- Никаких прогнозов цены\n"
        "- Никаких причинно-следственных выводов о будущем\n"
        "- Если сигнал помечен [КОНТРАРИАНСКИЙ] — указать что его полярность инвертирована\n"
        "- Пиши на русском языке\n\n"
        f"ТЕКУЩИЕ ЧИСЛОВЫЕ ЗНАЧЕНИЯ:\n{metrics_str}\n\n"
        f"АКТИВНЫЕ СИГНАЛЫ И ПАТТЕРНЫ MOZART:\n{context_str}\n\n"
        "ИТОГ ВЫРАВНИВАНИЯ:\n"
        f"  Вердикт: {alignment.verdict}\n"
        f"  Счёт: {alignment.score:+d} "
        f"(бычьих: {len(alignment.bullish)}, "
        f"медвежьих: {len(alignment.bearish)}, "
        f"нейтральных: {len(alignment.neutral)})\n"
        f"  Нет данных (missing): {missing_str}\n\n"
        "Напиши 3–5 предложений. Опиши что показывают активные метрики согласно\n"
        "методологии Mozart — без оценок, советов, прогнозов и рекомендаций.\n"
    )

    # --- Шаг 4: вызов Gemini API (google-genai SDK) ---
    api_key = os.environ.get("GOOGLE_API_KEY") or os.environ.get("GEMINI_API_KEY")
    client = genai.Client(api_key=api_key)
    response = client.models.generate_content(
        model="gemini-2.0-flash",
        contents=prompt,
        config=types.GenerateContentConfig(
            max_output_tokens=max_tokens,
            temperature=0.3,
        ),
    )
    return response.text
