# ---------------------------------------------------------------------------
# generate_alignment_summary()
# ---------------------------------------------------------------------------

def generate_alignment_summary(
    alignment: AlignmentResult,
    raw_metrics: dict[str, Optional[float]],
    max_tokens: int = 350,
) -> str:
    """
    Генерирует 3–5 предложений описания текущего состояния рынка
    на основе активных сигналов Mozart и числовых метрик.

    Args:
        alignment:   AlignmentResult из mozart_alignment.build_alignment().
        raw_metrics: Словарь числовых значений метрик.
                     Значения None → фильтруются, не попадают в промпт.
        max_tokens:  Максимум токенов ответа (default: 350 = ~3–5 предложений).

    Returns:
        str: 3–5 предложений на русском языке.
             НЕ содержит рекомендаций, советов, прогнозов цены.
             Описывает только факты и их значение по методологии Mozart.

    Raises:
        anthropic.APIError: при проблемах с API (таймаут, ошибка сети и т.д.).
            Оркестратор оборачивает вызов в try/except.

    TDD:
        Только smoke-test (tests/test_mozart_llm_smoke.py).
        Недетерминированный LLM-вывод не поддаётся unit-тестированию.
        Smoke проверяет: str, len > 50, нет 'None', нет слов-рекомендаций,
        ровно 1 вызов API.
    """
    # --- Шаг 1: Строим контекст только из активных сигналов ---
    active_ids = alignment.bullish + alignment.bearish + alignment.neutral
    context_lines: list[str] = []

    for sid in active_ids:
        ctx = SIGNAL_CONTEXT.get(sid)
        if ctx is None:
            # МБ-03 и другие без контекста — пропускаем, не инжектируем пустоту
            continue

        if sid in alignment.bullish:
            polarity = 'BULLISH'
        elif sid in alignment.bearish:
            polarity = 'BEARISH'
        else:
            polarity = 'NEUTRAL'

        contr_tag = ' [КОНТРАРИАНСКИЙ]' if sid in alignment.contrarian_flags else ''
        context_lines.append(f"  {sid} ({polarity}{contr_tag}): {ctx}")

    missing_str = ', '.join(alignment.missing) if alignment.missing else 'нет'
    context_str = '\n'.join(context_lines) if context_lines else '  (нет активных сигналов с описанием)'

    # --- Шаг 2: Форматируем числовые метрики — только не-None ---
    metrics_lines = [
        f"  {k}: {v}"
        for k, v in raw_metrics.items()
        if v is not None
    ]
    metrics_str = '\n'.join(metrics_lines) if metrics_lines else '  (данные недоступны)'

    # --- Шаг 3: Промпт ---
    prompt = f"""Ты аналитический ассистент криптовалютного трейдера.
Используй только методологию аналитика Mozart (цитаты из его постов ниже).

ПРАВИЛА ВЫВОДА — строго обязательны:
- Только факты и определения метрик по методологии Mozart
- Никаких торговых рекомендаций, советов, призывов к действию
- Никаких прогнозов цены
- Никаких причинно-следственных выводов о будущем
- Если сигнал помечен [КОНТРАРИАНСКИЙ] — указать что его полярность инвертирована
- Пиши на русском языке

ТЕКУЩИЕ ЧИСЛОВЫЕ ЗНАЧЕНИЯ:
{metrics_str}

АКТИВНЫЕ СИГНАЛЫ И ПАТТЕРНЫ MOZART:
{context_str}

ИТОГ ВЫРАВНИВАНИЯ:
  Вердикт: {alignment.verdict}
  Счёт: {alignment.score:+d} (бычьих: {len(alignment.bullish)}, медвежьих: {len(alignment.bearish)}, нейтральных: {len(alignment.neutral)})
  Нет данных (missing): {missing_str}

Напиши 3–5 предложений. Опиши что показывают активные метрики согласно
методологии Mozart — без оценок, советов, прогнозов и рекомендаций.
"""

    # --- Шаг 4: Вызов API ---
    client = anthropic.Anthropic()   # API key из переменной окружения ANTHROPIC_API_KEY
    response = client.messages.create(
        model="claude-haiku-4-5-20251001",   # haiku: быстро и дёшево для резюме
        max_tokens=max_tokens,
        messages=[{"role": "user", "content": prompt}],
    )
    return response.content[0].text
