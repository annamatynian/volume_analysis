# ---------------------------------------------------------------------------
# _fmt_metric() — форматирование float для промпта LLM
# ---------------------------------------------------------------------------

def _fmt_metric(v: float, is_usd: bool = False) -> str:
    """Форматирует числовое значение метрики перед передачей в промпт LLM.

    WHY: без форматирования LLM получает '-213722897.004' и воспроизводит
    '-213,722,897.00428572' в выводе. Читаемый формат устраняет нечитаемость.

    Args:
        v:       числовое значение метрики.
        is_usd:  True  -> префикс '$' (для USD-метрик, ключи с суффиксом '_usd').
                 False -> без '$' (для BTC, ratio, z-score и других не-USD).
                 WHY: ранее _fmt_metric добавляла '$' ко всем значениям >= 1M;
                 BTC-метрики (Net Pos 30d) получали '$1.0 млн' — LLM цитировала
                 как доллары вместо биткоинов (баг обнаружен прогоном 2026-05-26).

    Диапазоны (is_usd=True):  '$X.XX млрд' / '$X.X млн' / '$X,XXX.X' / '$X.XX'
    Диапазоны (is_usd=False): 'X.XX млрд'  / 'X.X млн'  / 'X,XXX.X'  / 'X.XX'
    """
    abs_v = abs(v)
    if is_usd:
        if abs_v >= 1_000_000_000:
            return "${:.2f} млрд".format(v / 1_000_000_000)
        if abs_v >= 1_000_000:
            return "${:.1f} млн".format(v / 1_000_000)
        if abs_v >= 1_000:
            return "${:,.1f}".format(v)
        return "${:.2f}".format(v)
    else:
        if abs_v >= 1_000_000_000:
            return "{:.2f} млрд".format(v / 1_000_000_000)
        if abs_v >= 1_000_000:
            return "{:.1f} млн".format(v / 1_000_000)
        if abs_v >= 1_000:
            return "{:,.1f}".format(v)
        return "{:.2f}".format(v)


# ---------------------------------------------------------------------------
# generate_alignment_summary()
# ---------------------------------------------------------------------------

def generate_alignment_summary(
    alignment: AlignmentResult,
    raw_metrics: dict[str, Optional[float]],
    signal_labels: dict[str, str] | None = None,
    max_tokens: int = 1200,
) -> str:
    """
    Генерирует 3–5 предложений описания текущего состояния рынка
    на основе активных сигналов Mozart и числовых метрик.

    Args:
        alignment:   AlignmentResult из mozart_alignment.build_alignment().
        raw_metrics: Словарь числовых значений метрик.
                     Значения None → фильтруются, не попадают в промпт.
        max_tokens:  Максимум видимых токенов вывода (default: 900).
                     WHY 1200 (не 900): при 15 активных сигналах × ~50 токенов
                     = 750 минимум; 900 доказанно обрезает НВ-02 и М-12
                     (прогон 2026-06-10). 1200 даёт запас.
                     WHY thinking_budget=0: Gemini 2.5 Flash без явного 0
                     тратит thinking-токены из бюджета max_output_tokens,
                     сокращая реальный вывод до 26 слов.

    Returns:
        str: 3–5 предложений на русском языке.
             НЕ содержит рекомендаций, советов, прогнозов цены.

    Raises:
        google.genai.errors.APIError: при проблемах с API.
            Оркестратор оборачивает вызов в try/except.

    TDD:
        Только smoke-test (tests/test_mozart_llm_smoke.py).
        Smoke: str, len > 50, нет 'None', нет слов-рекомендаций, 1 вызов API.
    """
    # --- Шаг 1: контекст только из активных сигналов ---
    # WHY ротация bearish: М-12 систематически пропускался при 4 медвежьих сигналах
    # (прогоны 2026-05-25, 2026-05-26): LLM обрабатывает сигналы по порядку
    # и сбрасывает последний. Решение: ставим М-12 первым в bearish-группе.
    _bearish = (
        [s for s in alignment.bearish if s == 'М-12']
        + [s for s in alignment.bearish if s != 'М-12']
    )
    active_ids = alignment.bullish + _bearish + alignment.neutral
    context_lines: list[str] = []

    for sid in active_ids:
        ctx = SIGNAL_CONTEXT.get(sid)
        if ctx is None:
            continue   # МБ-03 и другие без контекста

        if sid in alignment.bullish:
            polarity = 'BULLISH'
        elif sid in alignment.bearish:
            polarity = 'BEARISH'
        else:
            polarity = 'NEUTRAL'

        contr_tag = ' [КОНТРАРИАНСКИЙ]' if sid in alignment.contrarian_flags else ''
        context_lines.append(f"  {sid} ({polarity}{contr_tag}): {ctx}")

    missing_str = ', '.join(alignment.missing) if alignment.missing else 'нет'
    context_str = (
        '\n'.join(context_lines)
        if context_lines
        else '  (нет активных сигналов с описанием)'
    )

    # --- Шаг 2б: текущие строковые классификации — устраняет галлюцинации меток ---
    # WHY: LLM видит polarity (бычье/медвежье) но не знает текущее значение метки
    # (напр., DESCENDING_WEAK вместо STRONG, RISING для НВ-02) → галлюцинации
    labels_lines: list[str] = []
    if signal_labels:
        for sid, lbl in signal_labels.items():
            if lbl is not None:
                labels_lines.append(f"  {sid} = {lbl}")
    labels_str = (
        '\n'.join(labels_lines)
        if labels_lines
        else '  (метки не переданы)'
    )

    # --- Шаг 2: числовые метрики — только не-None, форматируем через _fmt_metric ---
    # WHY is_usd='_usd' in k: BTC-метрики (Net Pos 30d) не должны получать '$';
    # знак доллара применяется только к ключам с суффиксом '_usd'.
    metrics_lines = [
        f"  {k}: {_fmt_metric(v, is_usd='_usd' in k)}"
        for k, v in raw_metrics.items()
        if v is not None
    ]
    metrics_str = '\n'.join(metrics_lines) if metrics_lines else '  (данные недоступны)'

    # --- Шаг 3: промпт ---
    prompt = (
        "Ты аналитический ассистент криптовалютного трейдера.\n"
        "Используй только методологию аналитика Mozart (цитаты из его постов ниже).\n\n"
        "ПРАВИЛА ВЫВОДА — строго обязательны:\n"
        "- Только факты и определения метрик по методологии Mozart\n"
        "- Никаких торговых рекомендаций, советов, призывов к действию\n"
        "- Никаких прогнозов цены\n"
        "- Никаких причинно-следственных выводов о будущем\n"
        "- Если сигнал помечен [КОНТРАРИАНСКИЙ] — указать что его полярность инвертирована\n"
        "- Пиши на русском языке\n\n"
        f"ТЕКУЩИЕ КЛАССИФИКАЦИИ СИГНАЛОВ (используй эти значения, не изобретай другие):\n{labels_str}\n\n"
        f"ТЕКУЩИЕ ЧИСЛОВЫЕ ЗНАЧЕНИЯ:\n{metrics_str}\n\n"
        f"АКТИВНЫЕ СИГНАЛЫ И ПАТТЕРНЫ MOZART:\n{context_str}\n\n"
        "ИТОГ ВЫРАВНИВАНИЯ:\n"
        f"  Вердикт: {alignment.verdict}\n"
        f"  Счёт: {alignment.score:+d} "
        f"(бычьих: {len(alignment.bullish)}, "
        f"медвежьих: {len(alignment.bearish)}, "
        f"нейтральных: {len(alignment.neutral)})\n"
        f"  Нет данных (missing): {missing_str}\n\n"
        f"Список сигналов которые ОБЯЗАТЕЛЬНО нужно упомянуть: {', '.join(active_ids)}\n\n"
        "Напиши 3–5 предложений. Упомяни КАЖДЫЙ сигнал из списка выше без исключения.\n"
        "Опиши что показывают активные метрики согласно методологии Mozart\n"
        "— без оценок, советов, прогнозов и рекомендаций.\n"
    )

    # --- Шаг 4: вызов Gemini API (google-genai SDK) ---
    api_key = os.environ.get("GOOGLE_API_KEY") or os.environ.get("GEMINI_API_KEY")
    client = genai.Client(api_key=api_key)
    response = client.models.generate_content(
        model="gemini-2.5-flash",
        contents=prompt,
        config=types.GenerateContentConfig(
            max_output_tokens=max_tokens,
            temperature=0.3,
            # WHY thinking_budget=0: калибровка 2026-05-25 показала что Gemini 2.5 Flash
            # без этого параметра использует thinking tokens из бюджета
            # max_output_tokens, сокращая реальный вывод до 26 слов при лимите 600.
            # Для фактографического резюме CoT избыточен.
            thinking_config=types.ThinkingConfig(thinking_budget=0),
        ),
    )
    return response.text
